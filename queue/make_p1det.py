"""Write queue/p1det.tsv: check that the paper 1 steps made deterministic (19 Oct 2026) give identical results twice.

Changed steps: bootstrap weights now assigned to agencies in sorted order (agency_bootstrap, agency_event,
composition_check, revision_checks, worktype_mix, bunching cluster_bootstrap); vendor-shuffle placebo and the
example clusters use a hash order instead of random(); descriptives uses exact medians.
The queue runs the changed steps from scratch (cached placebo / split-harm files removed), keeps the reports,
runs them again from scratch, and compares the two runs (expected: every file identical).
Run on Chopin in the p1repro work tree:  egpq start queue/p1det.tsv
"""
from pathlib import Path

P1 = "$EGP/work/p1repro"
PROC = f"{P1}/data/processed"
LOOP = ('for i in $(seq 60); do out=$("$PY_CPU" bunching.py {s} 2>&1); rc=$?; echo "$out"; '
        '[ $rc -ne 0 ] && exit $rc; echo "$out" | grep -q "time budget" || {{ echo "complete after $i round(s)"; exit 0; }}; '
        'done; echo "still incomplete after 60 rounds"; exit 1')
STEPS = [("bunch_split_placebo", LOOP.format(s="split_placebo")), ("bunch_split", '"$PY_CPU" bunching.py split'),
         ("bunch_split_harm_aggregate", LOOP.format(s="split_harm_aggregate")),
         ("bunch_cluster_bootstrap", '"$PY_CPU" bunching.py cluster_bootstrap')] + \
        [(s, f'"$PY_CPU" {s}.py') for s in ("descriptives", "revision_checks", "agency_bootstrap", "agency_event",
                                             "composition_check", "worktype_mix")]
FILES = ("bunching_split.md bunching_split_monthly.csv split_clusters_sample_2558.csv split_clusters_sample_2563.csv "
         "split_clusters_sample_2568.csv bunching_cluster_boot.md bunching_cluster_boot.csv descriptives.md descriptives.csv "
         "revision_checks.md revision_boot.csv agency_bootstrap.md bunching_cluster_boot_agency.csv revision_boot_agency.csv "
         "agency_event.md bunching_event_monthly_agency.csv composition_check.md composition_check.csv "
         "worktype_mix.md worktype_mix.csv")
CLEAR = f"rm -rf {PROC}/_split_placebo {PROC}/_split_harm && echo cleared caches"

rows = []


def job(jid, after, hours, cwd, cmd):
    rows.append("\t".join([jid, "cpu_p1", ",".join(after) if after else "-", str(hours), cwd, cmd]))


for run in (1, 2):
    job(f"det{run}_clear", [], 0.2, P1, CLEAR)
    for name, cmd in STEPS:
        job(f"det{run}_{name}", [f"det{run}_clear"], 8, f"{P1}/src", cmd)
    job(f"det{run}_keep", [], 0.2, P1,
        f"rm -rf reports_det{run} && mkdir reports_det{run} && cd reports && cp {FILES} ../reports_det{run}/ ; ls ../reports_det{run} | wc -l")
job("det_compare", ["det1_keep", "det2_keep"], 0.5, "$REPO",
    f'"$PY_CPU" foundation/compare_reports.py {P1}/reports_det1 {P1}/reports_det2 --out {P1}/reports/_det_run1_vs_run2.md')

out = Path(__file__).with_name("p1det.tsv")
out.write_text("\n".join(["# Paper 1 determinism check. Generated by queue/make_p1det.py.",
                          "#!lane cpu_p1 threads=4 cpus=0-7"] + rows) + "\n", encoding="utf-8")
print(f"{out}: {len(rows)} jobs")
