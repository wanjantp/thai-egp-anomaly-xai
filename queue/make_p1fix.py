"""Write queue/p1fix.tsv: rerun the paper 1 analyses on Chopin after the first trip run (18 Oct 2026).

Fixes found in the trip run:
  * 8 aggregate steps in bunching.py stop by themselves after ~2 min ("time budget", exit 0); they are now
    rerun in a loop until they no longer print that message (each run continues with the missing years);
  * order: split_placebo before split; split_harm_aggregate / split_quality_aggregate before harm_fe;
    revision_checks before agency_bootstrap;
  * the comparison with the PC runs last.
clean and features are not rerun (their row counts match the PC). Run:  egpq start queue/p1fix.tsv
"""
from pathlib import Path

P1 = "$EGP/work/p1repro"
PC = "$EGP/work/pc_snapshot/reports"
LOOPED = {"split_placebo", "consolidation_aggregate", "split_harm_aggregate", "split_quality_aggregate",
          "harm_cells_aggregate", "did_aggregate", "split_placebo_T_aggregate", "unit_bins_aggregate"}
BUNCHING = ["aggregate", "estimate", "dib", "event",
            "unit_bins_aggregate", "cluster_bootstrap", "dib_spec_curve", "robust", "datadriven",
            "split_aggregate", "split_placebo", "split", "split_placebo_T_aggregate", "split_placebo_T",
            "unit_bands", "coverage", "consolidation_aggregate", "consolidation",
            "did_aggregate", "did_discount", "harm_cells_aggregate", "split_harm_aggregate",
            "split_quality_aggregate", "harm_fe", "split_harm"]
SECTION = ["revision_checks", "coverage_check", "descriptives", "agency_bootstrap", "agency_event", "excess_sources",
           "value_reallocation", "budget_at_threshold", "split_transition_months", "split_keys", "split_keys_hash",
           "carril_test", "split_cross_vendor", "did_inference", "did_ref_agency", "did_by_gov", "price_equality",
           "inflation_adjust", "composition_check", "worktype_mix", "check_specific_above500k", "make_giq_figures"]
# rerun an aggregate until it stops printing the time-budget message (at most 60 rounds)
LOOP = ('for i in $(seq 60); do out=$("$PY_CPU" bunching.py {s} 2>&1); rc=$?; echo "$out"; '
        '[ $rc -ne 0 ] && exit $rc; echo "$out" | grep -q "time budget" || {{ echo "complete after $i round(s)"; exit 0; }}; '
        'done; echo "still incomplete after 60 rounds"; exit 1')

rows = []


def job(jid, after, hours, cwd, cmd):
    rows.append("\t".join([jid, "cpu_p1", ",".join(after) if after else "-", str(hours), cwd, cmd]))


prev = None
for s in BUNCHING:
    cmd = LOOP.format(s=s) if s in LOOPED else f'"$PY_CPU" bunching.py {s}'
    job(f"p1_bunch_{s}", [], 12, f"{P1}/src", cmd)
for s in SECTION:
    job(f"p1_{s}", [], 8, f"{P1}/src", f'"$PY_CPU" {s}.py')
job("p1_vs_pc", [], 0.5, "$REPO",
    f'"$PY_CPU" foundation/compare_reports.py {PC} {P1}/reports --out {P1}/reports/_vs_pc.md')

head = ["# Paper 1 rerun after the trip run. Generated by queue/make_p1fix.py.",
        "#!lane cpu_p1 threads=4 cpus=0-7"]
out = Path(__file__).with_name("p1fix.tsv")
out.write_text("\n".join(head + rows) + "\n", encoding="utf-8")
print(f"{out}: {len(rows)} jobs")
