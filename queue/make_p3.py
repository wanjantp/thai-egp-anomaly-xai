"""Write queue/p3perm.tsv (pipeline test) and queue/p3real.tsv (the one real run) for paper 3 on Chopin.

Locked plan: project doc claude/p3-pre-analysis-plan.md, run order section 10. Code runs in the p1repro work tree
(where data/processed/p3 was built by src/p3_panel.py). Run p3perm first, check its report, then p3real:
  egpq start queue/p3perm.tsv      ->  reports/p3_cate_permuted.md, reports/p3_policy_permuted.md
  egpq start queue/p3real.tsv      ->  reports/p3_cate.md, reports/p3_policy.md
"""
from pathlib import Path

P1 = "$EGP/work/p1repro"
# econml / causalfe without changing any package already pinned in egp-xai (pip refuses if they would change)
DEPS = ('"$PY_CPU" -m pip freeze | grep -iE "^(numpy|pandas|scikit-learn|scipy|shap|lightgbm|pyarrow)==" > "$TMPDIR/pins.txt" && '
        '"$PY_CPU" -m pip install -c "$TMPDIR/pins.txt" econml==0.17.0 causalfe==0.3.2 && '
        '"$PY_CPU" -c "import econml, causalfe, sklearn, numpy; print(econml.__version__, causalfe.__version__, sklearn.__version__, numpy.__version__)" && '
        'cd src && "$PY_CPU" p3_fastcffe.py')
HEAD = ["#!lane cpu_p3a threads=8 cpus=0-7", "#!lane cpu_p3b threads=6 cpus=8-13"]


def write(name, flag, deps):
    rows = []
    if deps:
        rows.append("\t".join(["p3_deps", "cpu_p3a", "-", "0.5", P1, DEPS]))
    after = "p3_deps" if deps else "-"
    rows.append("\t".join([f"p3_cate{flag.replace('--', '_')}", "cpu_p3a", after, "16", f"{P1}/src", f'"$PY_CPU" p3_cate.py {flag}'.strip()]))
    rows.append("\t".join([f"p3_policy{flag.replace('--', '_')}", "cpu_p3b", after, "12", f"{P1}/src", f'"$PY_CPU" p3_policy.py {flag}'.strip()]))
    out = Path(__file__).with_name(name)
    out.write_text("\n".join([f"# Paper 3 {'pipeline test (permuted covariates)' if flag else 'real run'}. Generated by queue/make_p3.py."]
                             + HEAD + rows) + "\n", encoding="utf-8")
    print(f"{out}: {len(rows)} jobs")


write("p3perm.tsv", "--permute", True)
write("p3real.tsv", "", False)
